const fs=require('fs'),vm=require('vm'),assert=require('assert');
const src=fs.readFileSync(__dirname+'/app.js','utf8').replace(/ReactDOM\.createRoot\([\s\S]*$/,'');
const React={createElement(){},useState(){},useRef(){},useEffect(){},useMemo(){}};
const ctx={React,htm:()=>function(){return null},Chart:undefined,console,Date,Math,Number,String,Set,Map,location:{hash:''}};
vm.createContext(ctx);
vm.runInContext(src+'\nglobalThis.test={normalize,derive,toNum,pt,ds,calcEnergy,st};',ctx);
const {normalize,derive,toNum,pt,ds,calcEnergy,st}=ctx.test;
assert.strictEqual(toNum('1,234.50'),1234.5);
assert.strictEqual(toNum('12,34,567.89'),1234567.89);
assert.strictEqual(toNum('12abc'),null);
assert.strictEqual(toNum('—'),null);
let unitHeaders=normalize([{'Timestamp':'2026-11-07T12:00:00Z','Voltage RY (V)':400,'Current R (A)':12,'Neutral Current (A)':2}],['Timestamp','Voltage RY (V)','Current R (A)','Neutral Current (A)']);
assert.strictEqual(unitHeaders.mapped.includes('VRY'),true); assert.strictEqual(unitHeaders.mapped.includes('IR'),true); assert.strictEqual(unitHeaders.rows[0].IN,2);
let sparse=normalize([{Timestamp:'2026-11-07T12:00:00Z',Misc:'x'}],['Timestamp','Misc']); assert.strictEqual(sparse.rows.length,1); assert.strictEqual(sparse.rows[0].kW,undefined);
assert.strictEqual(pt(1700000000),1700000000000);
assert(Number.isNaN(pt('31/02/2026 12:00')));
let one=normalize([{Timestamp:'2026-11-07T12:00:00Z',V_R:230,I_R:10,kW:2,kVAR:-1,PF:0.89}],['Timestamp','V_R','I_R','kW','kVAR','PF']);
assert.strictEqual(one.rows.length,1);
assert(Math.abs(one.rows[0].VRY-230*Math.sqrt(3))<1e-8);
assert.strictEqual(one.rows[0].IRp,10);
assert.strictEqual(one.rows[0].lead,true);
let wyeAgain=derive({VRY:415,IR:17.320508});
let asDelta=derive(wyeAgain,{topology:'delta'}); assert.strictEqual(asDelta.VR,415); assert(Math.abs(asDelta.IRp-10)<1e-6);
let backToWye=derive(asDelta,{topology:'wye4'}); assert(Math.abs(backToWye.VR-415/Math.sqrt(3))<1e-8); assert(Math.abs(backToWye.IRp-17.320508)<1e-6);
let delta=derive({IR:17.320508,VRY:400}, {topology:'delta'});
assert(Math.abs(delta.IRp-10)<1e-6); assert.strictEqual(delta.VR,400);
let measuredNeutral=derive({INm:7.5}); assert.strictEqual(measuredNeutral.IN,7.5);
let p=derive({kW:3,kVAR:-4});
assert.strictEqual(p.kVA,5); assert.strictEqual(p.lead,true); assert.strictEqual(p.PF,-0.6);
let pfOnly=derive({kVA:10,PF:-0.8}); assert.strictEqual(pfOnly.kW,8); assert.strictEqual(pfOnly.kVAR,-6);
let e=calcEnergy([{t:0,kW:10,kVAR:-4,kVA:12},{t:3600000,kW:20,kVAR:-2,kVA:22}]);
assert.strictEqual(e.kWh,15); assert.strictEqual(e.kVArh,-3);
let rows=Array.from({length:65001},(_,i)=>({t:i,kW:i===32000?100:1,VRY:i===32001?100:230,IR:i===32002?500:10}));
let reduced=ds(rows,300,['kW','VRY','IR']);
assert(reduced.length<65001); assert(reduced.some(r=>r.kW===100)); assert(reduced.some(r=>r.VRY===100)); assert(reduced.some(r=>r.IR===500));
assert.strictEqual(st([{x:1},{x:3}],'x').avg,2);
console.log('All parser, 1-row, Wye/Delta, measured-neutral, power-triangle, energy, and 65,001-row downsampling tests passed.');
